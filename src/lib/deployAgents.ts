export async function generateNginxSite(opts?: {
  serverName?: string;
  port?: number;
}): Promise<{ path: string; content: string }> {
  const serverName = opts?.serverName || "_";
  const port = opts?.port || 3000;
  const content = `# Generated by AI Agent Pro — Phase 39
server {
    listen 80;
    server_name ${serverName};

    location / {
        proxy_pass http://127.0.0.1:${port};
        proxy_http_version 1.1;
        proxy_set_header Upgrade \\$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host \\$host;
        proxy_set_header X-Real-IP \\$remote_addr;
        proxy_set_header X-Forwarded-For \\$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \\$scheme;
    }
}
`;
  await writeWorkspaceFile("deploy/nginx.conf", content);
  pushLog({ action: "nginx_site", target: "local", ok: true, detail: "deploy/nginx.conf written" });
  return { path: "deploy/nginx.conf", content };
}

