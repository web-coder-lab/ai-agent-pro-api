/** Run a high-level deploy recipe */
export async function runDeployRecipe(
  recipe: "node-docker" | "node-pm2" | "static-nginx",
  opts?: { domain?: string; port?: number; vpsId?: string }
): Promise<{ steps: { step: string; ok: boolean; detail: string }[] }> {
  const steps: { step: string; ok: boolean; detail: string }[] = [];
  const port = opts?.port || 3000;

  if (recipe === "node-docker") {
    const df = await generateDockerfile({});
    steps.push({ step: "dockerfile", ok: true, detail: df.path });
    const cmp = await generateCompose({ port });
    steps.push({ step: "compose", ok: true, detail: cmp.path });
    if (!opts?.vpsId) {
      const tools = await detectTools();
      if (tools.docker) {
        const b = await dockerBuild();
        steps.push({ step: "build", ok: b.ok, detail: b.output.slice(0, 200) });
      } else {
        steps.push({ step: "build", ok: false, detail: "docker not installed" });
      }
    }
  } else if (recipe === "node-pm2") {
    const eco = await generatePm2Ecosystem({});
    steps.push({ step: "ecosystem", ok: true, detail: eco.path });
    const tools = await detectTools();
    if (tools.pm2 && !opts?.vpsId) {
      const p = await pm2Start();
      steps.push({ step: "pm2_start", ok: p.ok, detail: p.output.slice(0, 200) });
    } else {
      steps.push({ step: "pm2_start", ok: false, detail: tools.pm2 ? "skipped remote" : "pm2 not installed" });
    }
  } else if (recipe === "static-nginx") {
    const n = await generateNginxSite({ serverName: opts?.domain || "_", port });
    steps.push({ step: "nginx", ok: true, detail: n.path });
    const c = await generateCaddyfile({ domain: opts?.domain || "localhost", port });
    steps.push({ step: "caddy", ok: true, detail: c.path });
  }

  // optional remote copy hint via VPS
  if (opts?.vpsId) {
    try {
      const r = await execOnVps(opts.vpsId, "mkdir -p ~/app && echo READY");
      steps.push({
        step: "vps_prep",
        ok: r.code === 0,
        detail: (r.stdout || r.stderr).slice(0, 200),
      });
    } catch (e: any) {
      steps.push({ step: "vps_prep", ok: false, detail: e.message });
    }
  }

  log("info", `Deploy recipe ${recipe} steps=${steps.length}`, "deploy");
  return { steps };
}


