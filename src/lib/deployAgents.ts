export async function dockerBuild(tag = "ai-agent-pro:latest"): Promise<{ ok: boolean; output: string }> {
  const r = await runLocal("docker", ["build", "-t", tag, "."]);
  const ok = r.code === 0;
  pushLog({ action: "build", target: "local", ok, detail: (r.stderr || r.stdout).slice(0, 400) });
  return { ok, output: (r.stdout + "\n" + r.stderr).slice(0, 4000) };
}

export async function composeUp(): Promise<{ ok: boolean; output: string }> {
  let r = await runLocal("docker", ["compose", "up", "-d", "--build"]);
  if (r.code !== 0) {
    r = await runLocal("docker-compose", ["up", "-d", "--build"]);
  }
  const ok = r.code === 0;
  pushLog({ action: "up", target: "local", ok, detail: (r.stderr || r.stdout).slice(0, 400) });
  return { ok, output: (r.stdout + "\n" + r.stderr).slice(0, 4000) };
}

export async function composeDown(): Promise<{ ok: boolean; output: string }> {
  let r = await runLocal("docker", ["compose", "down"]);
  if (r.code !== 0) r = await runLocal("docker-compose", ["down"]);
  const ok = r.code === 0;
  pushLog({ action: "down", target: "local", ok, detail: (r.stderr || r.stdout).slice(0, 400) });
  return { ok, output: (r.stdout + "\n" + r.stderr).slice(0, 2000) };
}

