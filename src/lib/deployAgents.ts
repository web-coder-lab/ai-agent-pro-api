export async function generateDeployPack(opts?: {
  serviceName?: string;
  port?: number;
  domain?: string;
  nodeVersion?: string;
}) {
  const port = opts?.port || 3000;
  const df = await generateDockerfile({ nodeVersion: opts?.nodeVersion });
  const cmp = await generateCompose({ serviceName: opts?.serviceName, port });
  const pm2 = await generatePm2Ecosystem({ name: opts?.serviceName });
  const nginx = await generateNginxSite({ serverName: opts?.domain || "_", port });
  const caddy = await generateCaddyfile({ domain: opts?.domain || "localhost", port });
  return {
    files: [df.path, cmp.path, pm2.path, nginx.path, caddy.path],
    port,
    domain: opts?.domain,
  };
}

